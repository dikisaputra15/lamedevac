        <div data-info-section="overview">
            <p class="p-modal text-justify">
                Basic-Level medical treatment (Article 15) is the entry level of Laos's four public treatment levels. At the government level, this level is represented by the Small Hospital (ໂຮງໝໍນ້ອຍ); in an area where no Small Hospital yet exists, an informal village-level health unit (a village medic, village health volunteers, traditional healers, and basic medical equipment) provides basic care instead. Article 3 of the Law separately defines a &quot;Community Hospital&quot; (ໂຮງໝໍຂຸມຊົນ) as a basic-level facility that provides ongoing treatment and accepts referrals from Small Hospitals.
            </p>
            <p class="p-modal text-justify">
                <strong>Note:</strong> This level is often called &quot;Health Center&quot; in the 2016 JICA technical survey and in most English-language secondary reporting on Laos, but the Law on Medical Treatment itself does not use that term. We have also not fully resolved how &ldquo;Community Hospital&rdquo; and &ldquo;Small Hospital&rdquo; relate to each other in current practice &mdash; both are basic-level facility types named in the Law, but Articles 15&ndash;19 (the referral chain) describe the Small Hospital, not the Community Hospital, as the Basic-Level facility. For desktop research, search for &ldquo;Health Center,&rdquo; &ldquo;Small Hospital,&rdquo; and &ldquo;Community Hospital&rdquo; as possible renderings of the same basic-level facility, and record which term a source actually uses rather than trying to force a distinction.
            </p>
        </div>
        <div data-info-section="role">
