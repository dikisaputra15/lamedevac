        <div data-info-section="overview">
            <p class="p-modal text-justify">
                Advanced-Level medical treatment (Article 17) is the third of Laos's four public treatment levels. At the government level, this level is represented by the Provincial Hospital. There are currently between 13 and 17 provincial hospitals nationwide, one generally serving each province. By law, a Provincial Hospital accepts patients referred from a lower level (the District Hospital) and sits below only the Central Hospital / Specific Curative Center tier.
            </p>
            <p class="p-modal text-justify">
                <strong>Note:</strong> Article 12 of the Law on Medical Treatment also names &quot;Regional Hospital&quot; (ໂຮງໝໍພາກ) as a public facility type, positioned above Provincial Hospital and below the Highest level (Article 18) &mdash; but Article 12 explicitly defers the Regional Hospital's detailed standard to a separate regulation, which we have not located. This confirms, from the primary law itself, the 2016 JICA finding that Regional Hospital was &quot;not yet determined.&quot; Classify a Regional Hospital as Advanced Level, but record it as &ldquo;Advanced &mdash; self-identifies as Regional Hospital&rdquo; rather than plain Advanced, so it can be revisited if that separate regulation is later found.
            </p>
        </div>
        <div data-info-section="role">
            <ul>
                <li>Serve as the principal referral hospital for its province, receiving cases from district hospitals within the province</li>
                <li>Provide emergency care, including resuscitation and anesthesia, beyond the capability of district-level facilities</li>
                <li>Refer cases exceeding provincial capability to a central hospital or specific curative center</li>
            </ul>
        </div>
        <div data-info-section="services">
            <p><strong>Core Capability Areas</strong></p>
            <ul>
                <li>All District Hospital functions (internal medicine, surgery, obstetrics-gynecology, pediatrics), plus anesthesiology, ophthalmology, and ear-nose-throat (ENT) services</li>
                <li>Independent laboratory, pharmacy, and diagnostic imaging units</li>
                <li>Capability to perform major operations, including Cesarean section and other surgical procedures beyond district-level scope</li>
            </ul>
            <p><strong>Diagnostic &amp; Support Infrastructure</strong></p>
            <ul>
                <li>Independent clinical laboratory, pharmacy unit, and diagnostic imaging capability</li>
                <li>Emergency and resuscitation capacity</li>
            </ul>
            <p><strong>Typical Bed Capacity</strong></p>
            <ul>
                <li>50 to 250 beds; staffing benchmark of approximately one doctor per five beds</li>
            </ul>
            <p class="p-modal text-justify">
                <em><strong>Note:</strong> Legal basis: Law on Medical Treatment (Amended), Articles 12, 17 and 18. Bed/staffing detail sourced from JICA, Data Collection Survey on Health Sector in Lao PDR (2016).</em>
