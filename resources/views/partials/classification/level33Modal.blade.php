            <p class="p-modal text-justify">
                Intermediate-Level medical treatment (Article 16) is the second of Laos's four public treatment levels. At the government level, this level is represented by the District Hospital. By law, a District Hospital comprises doctors, nurses, midwives, assistant nurses, pharmacists and other medical professionals; has facilities, medical equipment and technicians; has the necessary laboratory capability; accepts referred patients; and treats illness in four core specialties: internal medicine, surgery, obstetrics-gynecology, and paediatrics. As of 2016, there were approximately 131 to 135 district hospitals nationwide.
            </p>
            <p class="p-modal text-justify">
                <strong>Note:</strong> The Law on Medical Treatment itself defines District Hospital as a single facility type (Intermediate Level) and does not split it into sub-grades. A separate 2016 JICA technical survey describes an operational/reporting &quot;Type A / Type B&quot; sub-grading in use at the time &mdash; Type A adding anesthesiology, ophthalmology and ENT capability, with major-operation capacity such as Cesarean section, over the Type B baseline of paediatrics, obstetrics-gynecology, dentistry, pharmacy and traditional medicine. Both sub-types typically operate 15&ndash;30 beds. Treat Type A/B as a useful practical signal, not an official legal category &mdash; for a formal classification, &ldquo;District Hospital&rdquo; (Intermediate Level) is correct regardless of sub-grade.
            </p>
        </div>
        <div data-info-section="role">
            <ul>
                <li>Serve as the principal inpatient referral point for Small Hospitals and village-level facilities within the district</li>
                <li>Provide district-level general medical, surgical, obstetric-gynecological, and paediatric care (the four core specialties required by Article 16)</li>
                <li>Refer cases exceeding district capability to the provincial hospital, and may not bypass the provincial level (Article 19).</li>
            </ul>
